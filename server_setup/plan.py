"""Turn wizard answers into Core's .env, firewall rules and the start script.

Standard mode = one machine, one API: Andromeda.Core with GAME_SESSION_PROVIDER=local
starts the native game server processes itself. Nothing here configures the
Orchestrator; its settings are removed from Core's .env when setup writes it.
"""

from __future__ import annotations

from dataclasses import dataclass
from pathlib import Path
from urllib.parse import urlparse

from .publicip import parse_public_ipv4

HTTP_MODES = ("ip", "tunnel", "domain")
FIREWALL_PREFIX = "Andromeda"
# Advanced two-API (Core + Orchestrator) settings. The single-server mode never writes them.
ORCHESTRATOR_KEYS = (
    "GAME_HOST_API_BASE_URL",
    "GAME_HOST_API_TOKEN",
    "GAME_HOST_API_TIMEOUT_SECONDS",
    "GAME_HOST_API_TRACE",
    "HOST_API_TOKEN",
)
ENV_HEADER = (
    "Generated by Andromeda server setup (Andromeda.Core/setup_server.py).\n"
    "Single-server mode: Core is the only API and starts game servers itself (GAME_SESSION_PROVIDER=local).\n"
    "Contains secrets: do not share or commit this file.\n"
    "Rerun setup to change it; unknown keys you add are preserved."
)
# Older generated files carry this marker too; run_server.bat leaves such files alone.
GENERATED_MARKERS = ("Generated by Andromeda server setup", "Generated by Andromeda.Orchestrator/setup.py")


@dataclass
class Plan:
    core_dir: Path
    install_root: Path
    public_host: str = ""
    http_mode: str = "ip"
    core_port: int = 8000
    port_start: int = 7777
    port_end: int = 7977
    max_sessions: int = 6
    game_exe: Path | None = None
    core_hostname: str = ""
    core_url: str = ""  # domain mode: the operator's public Core URL
    log_server: bool = False
    log_port: int = 9090
    landing_page: bool = False
    cloudflared: str = ""
    tunnel_config: Path | None = None
    tunnel_token_file: Path | None = None

    # --- derived values -------------------------------------------------
    @property
    def core_bind(self) -> str:
        # Behind a tunnel cloudflared connects over localhost, so Core need not listen publicly.
        return "127.0.0.1" if self.http_mode == "tunnel" else "0.0.0.0"

    @property
    def core_public_url(self) -> str:
        if self.http_mode == "tunnel":
            return f"https://{self.core_hostname}"
        if self.http_mode == "domain":
            return self.core_url
        return f"http://{self.public_host}:{self.core_port}"

    @property
    def core_local_url(self) -> str:
        """Game servers run on this machine, so they report to Core over localhost."""
        return f"http://127.0.0.1:{self.core_port}"

    @property
    def tunnel_routes(self) -> list[tuple[str, int]]:
        return [(self.core_hostname, self.core_port)] if self.core_hostname else []

    def game_port_pairs(self) -> int:
        start = self.port_start if self.port_start % 2 == 1 else self.port_start + 1
        return max(0, (self.port_end - start + 1) // 2)


def normalize_url(value: str, default_scheme: str = "https") -> str:
    value = value.strip().rstrip("/")
    if not value:
        raise ValueError("a URL is required")
    if "://" not in value:
        value = f"{default_scheme}://{value}"
    parsed = urlparse(value)
    if parsed.scheme not in ("http", "https") or not parsed.hostname:
        raise ValueError(f"invalid HTTP(S) address: {value}")
    return value


def validate(plan: Plan) -> list[str]:
    """Return configuration errors (empty list means the plan is usable)."""
    errors: list[str] = []
    if plan.http_mode not in HTTP_MODES:
        errors.append(f"HTTP mode must be one of {', '.join(HTTP_MODES)}")
    if not plan.public_host:
        errors.append("the public game address (SERVER_HOST) is not set")
    elif not parse_public_ipv4(plan.public_host):
        # Game/voice UDP goes straight to SERVER_HOST; a tunnel or proxied hostname cannot carry it.
        errors.append(
            f"SERVER_HOST {plan.public_host!r} must be this server's public IPv4 address "
            "(not a hostname, Cloudflare Tunnel domain or private/LAN address)"
        )

    named = {"Core port": plan.core_port}
    if plan.log_server:
        named["log collector port"] = plan.log_port
    for label, port in {**named, "game port range start": plan.port_start, "game port range end": plan.port_end}.items():
        if not 1 <= port <= 65535:
            errors.append(f"{label} {port} is outside 1-65535")
    if plan.port_start >= plan.port_end:
        errors.append("game port range start must be lower than its end")
    if plan.max_sessions < 1:
        errors.append("max sessions must be at least 1")
    elif plan.game_port_pairs() < plan.max_sessions:
        errors.append(
            f"game port range {plan.port_start}-{plan.port_end} only fits {plan.game_port_pairs()} sessions "
            f"(each needs a game+voice pair) but max sessions is {plan.max_sessions}"
        )
    seen: dict[int, str] = {}
    for label, port in named.items():
        if port in seen:
            errors.append(f"{label} and {seen[port]} both use port {port}")
        seen[port] = label
        if plan.port_start <= port <= plan.port_end:
            errors.append(f"{label} {port} overlaps the game port range {plan.port_start}-{plan.port_end}")

    if plan.http_mode == "tunnel" and not plan.core_hostname:
        errors.append("Cloudflare Tunnel mode needs a Core hostname")
    if plan.http_mode == "domain" and not plan.core_url:
        errors.append("custom domain mode needs the public Core URL")
    if plan.game_exe is None:
        errors.append("the game executable path (GAME_EXECUTABLE_PATH) is not set")
    elif not plan.game_exe.is_absolute():
        errors.append(f"GAME_EXECUTABLE_PATH {plan.game_exe} must be an absolute path")
    return errors


def core_env(plan: Plan, admin_password: str, steam_api_key: str | None) -> tuple[dict[str, object], dict[str, object]]:
    """Return (managed, defaults) for Andromeda.Core/.env in single-server mode."""
    managed: dict[str, object] = {
        # Resolve through the router dynamically when join/session data is built.
        "SERVER_IP": "auto",
        "SERVER_IP_CACHE_SECONDS": 30,
        # Compatibility snapshot for older 0.11.1 components.
        "SERVER_HOST": plan.public_host,
        "CORE_HOST": plan.core_bind,
        "CORE_PORT": plan.core_port,
        # Core starts and stops the native game processes itself; no Orchestrator.
        "GAME_SESSION_PROVIDER": "local",
        "GAME_RUNTIME_MODE": "process",
        "GAME_EXECUTABLE_PATH": str(plan.game_exe),
        "GAME_SESSION_API_URL": plan.core_local_url,
        "GAME_PORT_RANGE_START": plan.port_start,
        "GAME_PORT_RANGE_END": plan.port_end,
        "MAX_EOB_INSTANCES": plan.max_sessions,
        "GAME_HOST_BOOT_PROVIDER": "none",
        "ADMIN_PASSWORD": admin_password,
        "ENABLE_LANDING_PAGE": plan.landing_page,
        "ENABLE_LOG_SERVER": plan.log_server,
        "LOG_SERVER_PORT": plan.log_port,
    }
    if steam_api_key:
        managed["STEAM_API_KEY"] = steam_api_key
    defaults: dict[str, object] = {
        "STEAM_APP_ID": "999860",
        "ENABLE_UPNP": False,
        "ENABLE_API_REQUEST_LOGGING": False,
    }
    return managed, defaults


@dataclass(frozen=True)
class FirewallRule:
    name: str
    protocol: str
    ports: str
    reason: str


CORE_RULE = f"{FIREWALL_PREFIX} Core API"
LOG_RULE = f"{FIREWALL_PREFIX} log collector"
# Created by the earlier two-API setup; the single-server mode never opens it.
ORCHESTRATOR_RULE = f"{FIREWALL_PREFIX} Orchestrator API"


def firewall_rules(plan: Plan) -> list[FirewallRule]:
    span = f"{plan.port_start}-{plan.port_end}"
    rules = [
        FirewallRule(f"{FIREWALL_PREFIX} game+voice UDP", "UDP", span, "game and voice traffic (always required)"),
        FirewallRule(f"{FIREWALL_PREFIX} game TCP", "TCP", span, "game session TCP channel (always required)"),
    ]
    if plan.http_mode != "tunnel":
        rules.append(FirewallRule(CORE_RULE, "TCP", str(plan.core_port), "Core API and website (not needed with a tunnel)"))
    if plan.log_server:
        rules.append(FirewallRule(LOG_RULE, "TCP", str(plan.log_port), "optional client log collector"))
    return rules


def stale_rules(plan: Plan) -> list[str]:
    """Rule names to remove because this configuration must not open them."""
    names = [ORCHESTRATOR_RULE]
    if plan.http_mode == "tunnel":
        names.append(CORE_RULE)
    if not plan.log_server:
        names.append(LOG_RULE)
    return names


def netsh_delete(name: str) -> list[str]:
    return ["netsh", "advfirewall", "firewall", "delete", "rule", f"name={name}"]


def netsh_commands(rule: FirewallRule) -> list[list[str]]:
    """Delete-then-add keeps reruns from piling up duplicate rules."""
    return [
        netsh_delete(rule.name),
        [
            "netsh", "advfirewall", "firewall", "add", "rule", f"name={rule.name}", "dir=in",
            "action=allow", f"protocol={rule.protocol}", f"localport={rule.ports}", "profile=any",
        ],
    ]


def format_command(argv: list[str]) -> str:
    out = []
    for arg in argv:
        if "=" in arg and " " in arg:
            key, _, value = arg.partition("=")
            out.append(f'{key}="{value}"')
        elif any(ch.isspace() for ch in arg):
            out.append(f'"{arg}"')
        else:
            out.append(arg)
    return " ".join(out)


@dataclass(frozen=True)
class Service:
    title: str
    cwd: Path
    argv: list[str]


def venv_python(directory: Path, windows: bool) -> Path:
    return directory / "venv" / ("Scripts/python.exe" if windows else "bin/python")


def services(plan: Plan, windows: bool) -> list[Service]:
    result = [Service(
        "Andromeda Core",
        plan.core_dir,
        [str(venv_python(plan.core_dir, windows)), "main.py", "--host", plan.core_bind, "--port", str(plan.core_port)],
    )]
    if plan.http_mode == "tunnel" and plan.cloudflared and plan.tunnel_token_file is not None:
        result.append(Service(
            "Andromeda Cloudflare Tunnel",
            plan.install_root,
            [plan.cloudflared, "tunnel", "run", "--token-file", str(plan.tunnel_token_file)],
        ))
    elif plan.http_mode == "tunnel" and plan.cloudflared and plan.tunnel_config is not None:
        result.append(Service(
            "Andromeda Cloudflare Tunnel",
            plan.install_root,
            [plan.cloudflared, "tunnel", "--config", str(plan.tunnel_config), "run"],
        ))
    return result


def check_command(plan: Plan, windows: bool) -> list[str]:
    return [
        str(venv_python(plan.core_dir, windows)), str(plan.core_dir / "setup_server.py"),
        "--check", "--install-root", str(plan.install_root),
    ]


def _quoted_exe(argv: list[str]) -> str:
    # Always quoting the executable means cmd /k sees >2 quotes and strips only the outer pair.
    return f'"{argv[0]}" {format_command(argv[1:])}'.rstrip()


def render_windows_launcher(plan: Plan, svcs: list[Service]) -> str:
    lines = [
        "@echo off",
        "setlocal EnableExtensions",
        "rem Generated by Andromeda server setup - rerun setup to regenerate.",
        "rem Starts Andromeda Core, the only API on this server (it starts and stops the",
        "rem game server processes itself), plus the Cloudflare Tunnel when configured.",
        "title Andromeda launcher",
        "if defined ANDROMEDA_SKIP_CHECK goto start",
        _quoted_exe(check_command(plan, windows=True)),
        "if errorlevel 1 goto checkfailed",
        ":start",
    ]
    for svc in svcs:
        # cmd /k keeps the window open so errors stay readable.
        lines.append(f'start "{svc.title}" /D "{svc.cwd}" cmd /k "{_quoted_exe(svc.argv)}"')
    lines += [
        "echo.",
        "echo Andromeda Core is starting in its own window. Leave it open while people play;",
        "echo close that window (or press Ctrl+C in it) to stop Core.",
        "timeout /t 10 >nul",
        "exit /b 0",
        ":checkfailed",
        "echo.",
        "echo [ERROR] Fix the FAIL items above (or run the setup again), then start Andromeda again.",
        "echo         Set ANDROMEDA_SKIP_CHECK=1 to start without this check.",
        "pause",
        "exit /b 1",
    ]
    return "\r\n".join(lines) + "\r\n"


def _sh_quote(arg: str) -> str:
    return "'" + arg.replace("'", "'\\''") + "'"


def render_posix_launcher(plan: Plan, svcs: list[Service]) -> str:
    lines = [
        "#!/usr/bin/env bash",
        "# Generated by Andromeda server setup. Starts Andromeda Core (and the tunnel); Ctrl+C stops them.",
        "set -euo pipefail",
        'if [[ -z "${ANDROMEDA_SKIP_CHECK:-}" ]]; then',
        "  " + " ".join(_sh_quote(arg) for arg in check_command(plan, windows=False)),
        "fi",
        "trap 'kill 0' EXIT",
    ]
    for svc in svcs:
        quoted = " ".join(_sh_quote(arg) for arg in svc.argv)
        lines.append(f"(cd {_sh_quote(str(svc.cwd))} && exec {quoted}) &")
    lines.append("wait")
    return "\n".join(lines) + "\n"
